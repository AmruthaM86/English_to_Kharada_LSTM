import streamlit as st
import os
from utils.helper import load_css

# ==========================================
# Page Configuration
# ==========================================

st.set_page_config(
    page_title="Training Graphs",
    page_icon="📈",
    layout="wide"
)
load_css()
# ==========================================
# Paths
# ==========================================

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ICON = os.path.join(
    BASE_DIR,
    "assets",
    "icons",
    "graph.png"
)

LOSS_GRAPH = os.path.join(
    BASE_DIR,
    "models",
    "training_loss.png"
)

ACCURACY_GRAPH = os.path.join(
    BASE_DIR,
    "models",
    "training_accuracy.png"
)

# ==========================================
# Header
# ==========================================

col1, col2 = st.columns([1, 8])

with col1:
    if os.path.exists(ICON):
        st.image(ICON, width=70)

with col2:
    st.title("Training Graphs")

st.write(
    "Visualize the learning progress of the Seq2Seq Encoder–Decoder LSTM model."
)

st.divider()

# ==========================================
# Training Loss
# ==========================================

st.subheader("📉 Training Loss")

if os.path.exists(LOSS_GRAPH):

    st.image(
        LOSS_GRAPH,
        use_container_width=True
    )

    with open(LOSS_GRAPH, "rb") as file:

        st.download_button(
            "⬇ Download Training Loss Graph",
            data=file,
            file_name="training_loss.png",
            mime="image/png"
        )

else:

    st.warning("training_loss.png not found.")

st.divider()

# ==========================================
# Training Accuracy
# ==========================================

st.subheader("📈 Training Accuracy")

if os.path.exists(ACCURACY_GRAPH):

    st.image(
        ACCURACY_GRAPH,
        use_container_width=True
    )

    with open(ACCURACY_GRAPH, "rb") as file:

        st.download_button(
            "⬇ Download Training Accuracy Graph",
            data=file,
            file_name="training_accuracy.png",
            mime="image/png"
        )

else:

    st.warning("training_accuracy.png not found.")

st.divider()

# ==========================================
# Training Summary
# ==========================================

st.subheader("📋 Training Summary")

st.info("""
This page displays the graphs generated during model training.

**Training Loss**
- Shows how the model's error decreases over epochs.
- Lower values indicate better learning.

**Training Accuracy**
- Shows how accurately the model predicts during training.
- Higher values indicate better performance.

These graphs are automatically generated by `train.py`.
""")

st.divider()

st.success("Training graphs loaded successfully.")